"""Infer which room each ambient sensor is in, and write config/home.yaml.

    python -m pipeline.infer_sensor_rooms

The dataset does not publish a sensor -> room map, but it does publish where
each resident is (BLE beacons). For every "activity" event of a sensor (motion
detected, door opened, vibration, a power spike, a light change) we look up
which room the residents at home were in at that moment, and vote. The winning
room and its vote share are written to the config, so the report can show how
confident each mapping is.
"""
from __future__ import annotations

import re
import sys

import pandas as pd
import yaml

from shadowhome.schema import ACTIVITIES, EVENTS_FILE, HOME_CONFIG, ROOMS, USERS

# Floor-plan boxes for the dashboard (x, y, w, h on a 100 x 60 canvas).
# Schematic only: the dataset publishes no floor plan.
LAYOUT = {
    "bedroom":     [0, 0, 35, 30],
    "bathroom":    [0, 30, 20, 30],
    "hallway":     [20, 30, 25, 30],
    "study":       [35, 0, 25, 30],
    "kitchen":     [60, 0, 40, 25],
    "living_room": [45, 25, 55, 35],
}


def activity_events(ev: pd.DataFrame) -> pd.DataFrame:
    """Rows that mean 'someone did something near this sensor'."""
    t = ev["sensor_type"].astype(str)
    out = [ev[(t == "movement") & (ev["value"] == 1)],
           ev[(t == "contact") & (ev["value"] == 0)],
           ev[t == "vibration"]]
    for kind, rel in (("power", 1.5), ("illuminance", 1.5)):
        e = ev[t == kind].sort_values("ts")
        jump = e.groupby("sensor_id", observed=True)["value"].transform(
            lambda v: v > rel * v.rolling(20, min_periods=1).median().shift().fillna(v.median()) + 1)
        out.append(e[jump])
    return pd.concat(out).sort_values("ts")


def main() -> int:
    ev = pd.read_parquet(EVENTS_FILE)
    ev["ts"] = pd.to_datetime(ev["ts"], utc=True)
    acts = activity_events(ev)[["ts", "sensor_id", "sensor_type"]]
    pres = ev[ev["sensor_type"].astype(str) == "presence"][["ts", "sensor_id", "room"]]

    # Room of every resident at each event (BLE fix at most 2 minutes old).
    m = acts
    for user in USERS:
        p = pres[pres["sensor_id"].astype(str) == user][["ts", "room"]].sort_values("ts")
        m = pd.merge_asof(m, p.rename(columns={"room": user}), on="ts",
                          direction="backward", tolerance=pd.Timedelta(minutes=2))
    rooms = m[USERS].astype(str).where(m[USERS].astype(str).isin(ROOMS))
    # A vote only counts when it is unambiguous: one resident at home, or both in one room.
    unique = rooms.nunique(axis=1) == 1
    m["room"] = rooms.bfill(axis=1).iloc[:, 0]
    v = m[unique & m["room"].notna()]
    # Normalise by how often people are in each room at all (bedroom would win everything).
    base = v["room"].value_counts(normalize=True)

    sensors = {}
    all_ids = ev[~ev["sensor_type"].astype(str).isin(["presence", "bpm", "steps"])]
    for sid, kinds in all_ids.groupby("sensor_id", observed=True)["sensor_type"]:
        kind = sorted(set(map(str, kinds)))
        kind = "temphum" if "temperature" in kind else kind[0]
        counts = v[v["sensor_id"].astype(str) == str(sid)]["room"].astype(str).value_counts()
        if counts.sum() >= 20:
            lift = (counts / counts.sum()) / base.reindex(counts.index)
            room = str(lift.idxmax())
            share = round(float(counts[room] / counts.sum()), 2)
        else:
            room, share = "unknown", 0.0
        sensors[str(sid)] = {"type": kind, "room": room, "vote_share": share,
                             "lift": round(float(share / base.get(room, 1)), 1) if room != "unknown" else 0.0,
                             "votes": int(counts.sum())}
        print(f"{sid:>4} {kind:<12} -> {room:<12} share={share:.2f} lift={(share / base.get(room, 1)) if room != "unknown" else 0:.1f} votes={int(counts.sum())}")

    cfg = {
        "rooms": {r: {"box": LAYOUT[r]} for r in ROOMS},
        "residents": USERS,
        "activities": ACTIVITIES,
        "sensors": dict(sorted(sensors.items(), key=lambda kv: (re.sub(r"\d", "", kv[0]), int(re.sub(r"\D", "", kv[0]) or 0)))),
    }
    HOME_CONFIG.parent.mkdir(parents=True, exist_ok=True)
    with open(HOME_CONFIG, "w") as f:
        f.write("# Generated by `python -m pipeline.infer_sensor_rooms`; safe to hand-edit.\n")
        yaml.safe_dump(cfg, f, sort_keys=False, allow_unicode=True)
    print(f"wrote {HOME_CONFIG}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
